def table_gate(out: Path) -> dict:
    values = {}
    lines = [
        "% generated by scripts/make_results_assets.py -- do not edit",
        "\\begin{tabular}{llrrr}",
        "\\hline",
        "Dataset & Test condition & Balanced acc. & SD & Chance \\\\",
        "\\hline",
    ]
    for dataset in ("fetal_planes", "bus_bra"):
        frame = load(RUNS / "step4_gate" / dataset)
        if frame is None:
            continue
        for i, variant in enumerate(("a_full", "a_removed", "ctrl_random", "a_only")):
            name = PRETTY[dataset] if i == 0 else ""
            lines.append(
                f"{name} & {VARIANT_LABEL[variant]} & {cell(frame, variant):.4f} & "
                f"{cell_sd(frame, variant):.4f} & {cell(frame, variant, 'chance_balanced_accuracy'):.4f} \\\\"
            )
            values[f"{dataset}_{variant}"] = cell(frame, variant)
        drop, drop_sd = paired_drop(frame, "a_full", "a_removed")
        ctrl, _ = paired_drop(frame, "a_full", "ctrl_random")
        values[f"{dataset}_removal_drop"] = drop
        values[f"{dataset}_ctrl_drop"] = ctrl
        values[f"{dataset}_run_sd"] = cell_sd(frame, "a_full")
        lines.append("\\hline")
    lines.append("\\end{tabular}")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    return values


def table_annotation_only(out: Path) -> dict:
    values = {}
    lines = [
        "% generated by scripts/make_results_assets.py -- do not edit",
        "\\begin{tabular}{lrrrr}",
        "\\hline",
        "Dataset & \\Aonly{} bal.\\ acc. & SD & Chance & Ratio \\\\",
        "\\hline",
    ]
    for dataset in ("fetal_planes", "bus_bra"):
        frame = load(RUNS / "step4b" / dataset)
        if frame is None:
            continue
        score = cell(frame, "a_only")
        chance = cell(frame, "a_only", "chance_balanced_accuracy")
        lines.append(
            f"{PRETTY[dataset]} & {score:.4f} & {cell_sd(frame, 'a_only'):.4f} & "
            f"{chance:.4f} & {score / chance:.1f}$\\times$ \\\\"
        )
        values[f"{dataset}_aonly_trained"] = score
        values[f"{dataset}_aonly_ratio"] = score / chance
    lines += ["\\hline", "\\end{tabular}"]
    out.write_text("\n".join(lines) + "\n")
    return values


def table_positive_control(out: Path) -> tuple[dict, list]:
    values, curve = {}, []
    lines = [
        "% generated by scripts/make_results_assets.py -- do not edit",
        "\\begin{tabular}{lrrrr}",
        "\\hline",
        "Marker--label correlation & \\Afull{} & marker removed & Removal cost & \\Aonly{} \\\\",
        "\\hline",
    ]
    for strength in STRENGTHS:
        frame = load(RUNS / "step4c" / f"strength_{strength}" / "fetal_planes")
        if frame is None:
            continue
        full = cell(frame, "a_full")
        nomark = cell(frame, "a_full__nomarker")
        drop, drop_sd = paired_drop(frame, "a_full", "a_full__nomarker")
        only = cell(frame, "a_only")
        lines.append(f"{strength} & {full:.4f} & {nomark:.4f} & \\textbf{{{drop:+.4f}}} & {only:.4f} \\\\")
        curve.append({"strength": float(strength), "drop": drop, "drop_sd": drop_sd,
                      "a_full": full, "a_nomarker": nomark, "a_only": only})
        values[f"synth_drop_{strength.replace('.', 'p')}"] = drop
        values[f"synth_aonly_{strength.replace('.', 'p')}"] = only
    lines += ["\\hline", "\\end{tabular}"]
    out.write_text("\n".join(lines) + "\n")
    return values, curve


