def fig_sensitivity(out: Path, curve: list, real_drop: float, run_sd: float) -> None:
    """Removal cost against marker--label correlation, with the real annotations
    placed on the same axis.

    This is the paper's central figure: it converts "we found nothing" into
    "we found nothing, and here is exactly how much we would have found".
    """
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    curve = sorted(curve, key=lambda c: c["strength"])
    x = [c["strength"] for c in curve]
    y = [c["drop"] for c in curve]
    err = [c["drop_sd"] if np.isfinite(c["drop_sd"]) else 0.0 for c in curve]

    fig, ax = plt.subplots(figsize=(5.4, 3.2))
    ax.axhspan(-2 * run_sd, 2 * run_sd, color="0.88", zorder=0,
               label=f"$\\pm2\\times$ run-to-run SD ({run_sd:.4f})")
    ax.errorbar(x, y, yerr=err, marker="o", capsize=3, linewidth=1.6,
                color="#1f77b4", label="synthetic shortcut", zorder=3)
    ax.axhline(real_drop, color="#d62728", linestyle="--", linewidth=1.6, zorder=2,
               label=f"real annotations ({real_drop:+.4f})")

    ax.set_xlabel("marker–label correlation (shortcut strength)", fontsize=9)
    ax.set_ylabel("cost of removing the feature\n(balanced accuracy)", fontsize=9)
    ax.set_xticks(x)
    ax.tick_params(labelsize=8)
    ax.spines[["top", "right"]].set_visible(False)
    ax.legend(fontsize=7.5, frameon=False, loc="upper left")
    fig.tight_layout()

    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out.with_suffix(".pdf"), bbox_inches="tight")
    fig.savefig(out.with_suffix(".png"), dpi=200, bbox_inches="tight")
    plt.close(fig)


# --------------------------------------------------------------------------


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--paper", type=Path, default=None)
    args = parser.parse_args()
    paper = args.paper or find_paper_dir()
    print(f"manuscript: {paper}")

    values = {}
    values.update(table_gate(paper / "tables" / "gate_matrix.tex"))
    values.update(table_annotation_only(paper / "tables" / "annotation_only.tex"))
    control_values, curve = table_positive_control(paper / "tables" / "positive_control.tex")
    values.update(control_values)
    print("  tables/gate_matrix.tex, annotation_only.tex, positive_control.tex")

    real_drop = values.get("fetal_planes_removal_drop", float("nan"))
    run_sd = values.get("fetal_planes_run_sd", float("nan"))
    fig_sensitivity(paper / "figures" / "fig4_sensitivity", curve, real_drop, run_sd)
    print("  figures/fig4_sensitivity.pdf")

    # How many times more sensitive the design is than the effect it found --
    # the single number that converts the null from uninterpretable to strong.
    strongest = max((c["drop"] for c in curve), default=float("nan"))
    values["sensitivity_ratio"] = abs(strongest / real_drop) if real_drop else float("nan")
    values["strongest_drop"] = strongest

    macro = {
        "fetal_planes_a_full": "GateFetalFull", "fetal_planes_a_removed": "GateFetalRemoved",
        "fetal_planes_a_only": "GateFetalOnly", "fetal_planes_ctrl_random": "GateFetalCtrl",
        "bus_bra_a_full": "GateBusFull", "bus_bra_a_removed": "GateBusRemoved",
        "bus_bra_a_only": "GateBusOnly", "bus_bra_ctrl_random": "GateBusCtrl",
        "fetal_planes_removal_drop": "RealRemovalDrop", "fetal_planes_ctrl_drop": "RealCtrlDrop",
        "fetal_planes_run_sd": "RunSD",
        "fetal_planes_aonly_trained": "AonlyTrainedFetal", "fetal_planes_aonly_ratio": "AonlyRatioFetal",
        "bus_bra_aonly_trained": "AonlyTrainedBus",
        "synth_drop_1p0": "SynthDropOne", "synth_drop_0p75": "SynthDropSevenFive",
        "synth_drop_0p5": "SynthDropFive", "synth_drop_0p25": "SynthDropTwoFive",
        "synth_aonly_1p0": "SynthOnlyOne", "synth_aonly_0p75": "SynthOnlySevenFive",
        "strongest_drop": "StrongestDrop", "sensitivity_ratio": "SensitivityRatio",
    }
    lines = ["% generated by scripts/make_results_assets.py -- do not edit"]
    for key, name in macro.items():
        value = values.get(key)
        if value is None or not np.isfinite(value):
            continue
        if name == "SensitivityRatio":
            text = f"{value:,.0f}".replace(",", "{,}")
        elif name == "AonlyRatioFetal":
            text = f"{value:.1f}"
        elif "Drop" in name or name == "RunSD":
            text = f"{value:+.4f}" if "Drop" in name else f"{value:.4f}"
        else:
            text = f"{value:.4f}"
        lines.append(f"\\newcommand{{\\{name}}}{{{text}}}")
    (paper / "generated" / "results_values.tex").parent.mkdir(parents=True, exist_ok=True)
    (paper / "generated" / "results_values.tex").write_text("\n".join(lines) + "\n")
    print(f"  generated/results_values.tex ({len(lines) - 1} macros)")

    (paper / "generated" / "results_values.json").write_text(json.dumps(values, indent=2))
    print(f"\nsensitivity ratio: the design detects a shortcut {values['sensitivity_ratio']:,.0f}x "
          f"larger than the real annotation effect")


if __name__ == "__main__":
    main()
