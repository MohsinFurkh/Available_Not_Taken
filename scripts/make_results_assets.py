def table_gate(out: Path) -> dict:
    values = {}
    lines = [
        "% generated by scripts/make_results_assets.py -- do not edit",
        "\\begin{tabular}{llrrrrr}",
        "\\hline",
        "Dataset & Test condition & Bal.\\ acc. & SD & Macro-$F_1$ & ECE & Chance \\\\",
        "\\hline",
    ]
    for dataset in ("fetal_planes", "bus_bra"):
        frame = load(RUNS / "step4_gate" / dataset)
        if frame is None:
            continue
        for i, variant in enumerate(("a_full", "a_removed", "ctrl_random", "a_only")):
            name = PRETTY[dataset] if i == 0 else ""
            lines.append(
                f"{name} & {VARIANT_LABEL[variant]} & {cell(frame, variant):.4f} & "
                f"{cell_sd(frame, variant):.4f} & {cell(frame, variant, 'macro_f1'):.4f} & "
                f"{cell(frame, variant, 'ece'):.4f} & "
                f"{cell(frame, variant, 'chance_balanced_accuracy'):.4f} \\\\"
            )
            values[f"{dataset}_{variant}"] = cell(frame, variant)
        drop, drop_sd = paired_drop(frame, "a_full", "a_removed")
        ctrl, ctrl_sd = paired_drop(frame, "a_full", "ctrl_random")
        values[f"{dataset}_removal_drop"] = drop
        values[f"{dataset}_removal_drop_sd"] = drop_sd
        values[f"{dataset}_ctrl_drop"] = ctrl
        # Marginal SD of A-full, kept only for context. The contrast is paired
        # on identical weights and subjects, so the paired-difference SD is the
        # correct yardstick; comparing a paired effect against an unpaired SD
        # understates the design's own sensitivity by about a factor of three.
        values[f"{dataset}_marginal_sd"] = cell_sd(frame, "a_full")
        values[f"{dataset}_paired_sd"] = drop_sd
        # TOST equivalence against a pre-specified margin. Converts "we found
        # nothing" into "we demonstrated equivalence within +/-delta", which is
        # a categorically stronger and more citable claim than a failed test.
        values.update(_tost(frame, dataset, margin=0.005))
        lines.append("\\hline")
    lines.append("\\end{tabular}")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    return values


def table_annotation_only(out: Path) -> dict:
    values = {}
    lines = [
        "% generated by scripts/make_results_assets.py -- do not edit",
        "\\begin{tabular}{lrrrr}",
        "\\hline",
        "Dataset & \\Aonly{} bal.\\ acc. & SD & Chance & Ratio \\\\",
        "\\hline",
    ]
    for dataset in ("fetal_planes", "bus_bra"):
        frame = load(RUNS / "step4b" / dataset)
        if frame is None:
            continue
        score = cell(frame, "a_only")
        chance = cell(frame, "a_only", "chance_balanced_accuracy")
        lines.append(
            f"{PRETTY[dataset]} & {score:.4f} & {cell_sd(frame, 'a_only'):.4f} & "
            f"{chance:.4f} & {score / chance:.1f}$\\times$ \\\\"
        )
        values[f"{dataset}_aonly_trained"] = score
        values[f"{dataset}_aonly_ratio"] = score / chance
    lines += ["\\hline", "\\end{tabular}"]
    out.write_text("\n".join(lines) + "\n")
    return values


def table_positive_control(out: Path) -> tuple[dict, list]:
    values, curve, rows_pending = {}, [], []
    lines = [
        "% generated by scripts/make_results_assets.py -- do not edit",
        "\\begin{tabular}{lrrrrr}",
        "\\hline",
        "Correlation $\\rho$ & \\Afull{} & marker removed & Removal cost (SD) & $p_{\\mathrm{adj}}$ & \\Aonly{} \\\\",
        "\\hline",
    ]
    for strength in STRENGTHS:
        frame = load(RUNS / "step4c" / f"strength_{strength}" / "fetal_planes")
        if frame is None:
            continue
        full = cell(frame, "a_full")
        nomark = cell(frame, "a_full__nomarker")
        drop, drop_sd = paired_drop(frame, "a_full", "a_full__nomarker")
        only = cell(frame, "a_only")
        rows_pending.append((strength, full, nomark, drop, drop_sd, only))
        pivot = frame.pivot_table(index=["fold", "seed"], columns="test_variant", values="balanced_accuracy")
        n_pairs = int((pivot["a_full"] - pivot["a_full__nomarker"]).dropna().shape[0]) \
            if "a_full__nomarker" in pivot else 0
        curve.append({"strength": float(strength), "drop": drop, "drop_sd": drop_sd,
                      "n_pairs": n_pairs, "a_full": full, "a_nomarker": nomark, "a_only": only})
        values[f"synth_drop_{strength.replace('.', 'p')}"] = drop
        values[f"synth_aonly_{strength.replace('.', 'p')}"] = only
    values["_rows_pending"] = rows_pending
    values["_lines"] = lines
    values["_out"] = str(out)
    return values, curve


def finish_positive_control(values: dict, curve: list) -> None:
    """Emit the table once Holm-adjusted p-values exist."""
    lines = values.pop("_lines")
    out = Path(values.pop("_out"))
    by_strength = {str(c["strength"]): c for c in curve}
    for strength, full, nomark, drop, drop_sd, only in values.pop("_rows_pending"):
        entry = by_strength.get(str(float(strength)), {})
        p_adj = entry.get("p_adj", float("nan"))
        p_text = "--" if not np.isfinite(p_adj) else (f"{p_adj:.3f}" if p_adj >= 0.001 else "<0.001")
        lines.append(
            f"{strength} & {full:.4f} & {nomark:.4f} & "
            f"\\textbf{{{drop:+.4f}}} ({drop_sd:.4f}) & {p_text} & {only:.4f} \\\\"
        )
    lines += ["\\hline", "\\end{tabular}"]
    out.write_text("\n".join(lines) + "\n")


