def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--paper", type=Path, default=None)
    args = parser.parse_args()
    paper = args.paper or find_paper_dir()
    print(f"manuscript: {paper}")

    values = {}
    values.update(table_gate(paper / "tables" / "gate_matrix.tex"))
    values.update(table_annotation_only(paper / "tables" / "annotation_only.tex"))
    control_values, curve = table_positive_control(paper / "tables" / "positive_control.tex")
    values.update(control_values)
    print("  tables/gate_matrix.tex, annotation_only.tex, positive_control.tex")

    real_drop = values.get("fetal_planes_removal_drop", float("nan"))
    run_sd = values.get("fetal_planes_paired_sd", float("nan"))
    fig_sensitivity(paper / "figures" / "fig4_sensitivity", curve, real_drop, run_sd)
    print("  figures/fig4_sensitivity.pdf")

    # A ratio against an effect argued to be indistinguishable from zero is
    # governed by rounding -- at -0.0001 the same division prints "3253x". What
    # the calibration actually licenses is a *detection threshold*: the weakest
    # cue whose removal cost clears the noise, and the strongest cue that does
    # not. Report that interval instead.
    strongest = max((c["drop"] for c in curve), default=float("nan"))
    values["strongest_drop"] = strongest
    # Detection is judged against each point's OWN paired variability, by a
    # one-sample t-test of its paired differences against zero. Using a single
    # pooled SD would call rho=0.5 detected on the strength of the gate's much
    # tighter noise, which is not the same experiment.
    from scipy import stats as sps

    for c in curve:
        n = c.get("n_pairs", 6)
        se = c["drop_sd"] / np.sqrt(n) if c["drop_sd"] and n else float("nan")
        c["t"] = c["drop"] / se if se and np.isfinite(se) and se > 0 else float("nan")
        c["p"] = float(sps.t.sf(abs(c["t"]), n - 1) * 2) if np.isfinite(c.get("t", np.nan)) else float("nan")
        c["detected"] = bool(np.isfinite(c["p"]) and c["p"] < 0.05 and c["drop"] > 0)
    # Holm-Bonferroni across the sweep. Four strengths are four tests, and the
    # protocol commits to correcting across the declared family; rho=0.5 reaches
    # p=0.034 unadjusted and does not survive correction.
    sys.path.insert(0, str(REPO / "src"))
    from asa.eval.stats import holm_bonferroni

    corrected = holm_bonferroni({str(c["strength"]): c["p"] for c in curve if np.isfinite(c.get("p", np.nan))})
    for c in curve:
        entry = corrected.get(str(c["strength"]), {})
        c["p_adj"] = entry.get("p_adjusted", float("nan"))
        c["detected"] = bool(entry.get("reject", False) and c["drop"] > 0)

    detected = [c for c in curve if c["detected"]]
    missed = [c for c in curve if not c["detected"]]
    values["mde_lower"] = max((c["drop"] for c in missed), default=float("nan"))
    values["mde_upper"] = min((c["drop"] for c in detected), default=float("nan"))
    values["mde_strength_detected"] = min((c["strength"] for c in detected), default=float("nan"))
    values["mde_strength_missed"] = max((c["strength"] for c in missed), default=float("nan"))

    finish_positive_control(values, curve)
    print("  tables/positive_control.tex (with Holm-adjusted p)")

    macro = {
        "fetal_planes_a_full": "GateFetalFull", "fetal_planes_a_removed": "GateFetalRemoved",
        "fetal_planes_a_only": "GateFetalOnly", "fetal_planes_ctrl_random": "GateFetalCtrl",
        "bus_bra_a_full": "GateBusFull", "bus_bra_a_removed": "GateBusRemoved",
        "bus_bra_a_only": "GateBusOnly", "bus_bra_ctrl_random": "GateBusCtrl",
        "fetal_planes_removal_drop": "RealRemovalDrop", "fetal_planes_ctrl_drop": "RealCtrlDrop",
        "fetal_planes_run_sd": "RunSD",
        "fetal_planes_aonly_trained": "AonlyTrainedFetal", "fetal_planes_aonly_ratio": "AonlyRatioFetal",
        "bus_bra_aonly_trained": "AonlyTrainedBus",
        "synth_drop_1p0": "SynthDropOne", "synth_drop_0p75": "SynthDropSevenFive",
        "synth_drop_0p5": "SynthDropFive", "synth_drop_0p25": "SynthDropTwoFive",
        "synth_aonly_1p0": "SynthOnlyOne", "synth_aonly_0p75": "SynthOnlySevenFive",
        "strongest_drop": "StrongestDrop",
        "fetal_planes_paired_sd": "PairedSD", "fetal_planes_marginal_sd": "MarginalSD",
        "mde_lower": "MDELower", "mde_upper": "MDEUpper",
        "mde_strength_detected": "MDEStrengthDetected",
        "mde_strength_missed": "MDEStrengthMissed",
        "fetal_planes_tost_margin": "TOSTMargin", "fetal_planes_tost_p": "TOSTP",
        "bus_bra_tost_p": "TOSTPBus",
    }
    lines = ["% generated by scripts/make_results_assets.py -- do not edit"]
    for key, name in macro.items():
        value = values.get(key)
        if value is None or not np.isfinite(value):
            continue
        if name in ("TOSTP", "TOSTPBus"):
            text = f"{value:.4f}" if value >= 0.0001 else "<0.0001"
        elif name in ("MDEStrengthDetected", "MDEStrengthMissed", "TOSTMargin"):
            text = f"{value:g}"
        elif name in ("PairedSD", "MarginalSD"):
            text = f"{value:.4f}"
        elif name in ("MDELower", "MDEUpper"):
            text = f"{value:+.4f}"
        elif name == "AonlyRatioFetal":
            text = f"{value:.1f}"
        elif "Drop" in name or name == "RunSD":
            text = f"{value:+.4f}" if "Drop" in name else f"{value:.4f}"
        else:
            text = f"{value:.4f}"
        lines.append(f"\\newcommand{{\\{name}}}{{{text}}}")
    (paper / "generated" / "results_values.tex").parent.mkdir(parents=True, exist_ok=True)
    (paper / "generated" / "results_values.tex").write_text("\n".join(lines) + "\n")
    print(f"  generated/results_values.tex ({len(lines) - 1} macros)")

    (paper / "generated" / "results_values.json").write_text(json.dumps(values, indent=2))
    print(f"\npaired SD           : {values.get('fetal_planes_paired_sd', float('nan')):.4f} "
          f"(marginal was {values.get('fetal_planes_marginal_sd', float('nan')):.4f})")
    print(f"detection threshold : between {values.get('mde_lower', float('nan')):+.4f} "
          f"(rho={values.get('mde_strength_missed', float('nan')):g}, missed) and "
          f"{values.get('mde_upper', float('nan')):+.4f} "
          f"(rho={values.get('mde_strength_detected', float('nan')):g}, detected)")
    print(f"TOST vs +/-{values.get('fetal_planes_tost_margin', 0.005):g}: "
          f"p={values.get('fetal_planes_tost_p', float('nan')):.4g} "
          f"-> {'EQUIVALENT' if values.get('fetal_planes_tost_equivalent') else 'not shown'}")


if __name__ == "__main__":
    main()
