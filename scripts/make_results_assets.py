#!/usr/bin/env python
"""Turn runs/ into the manuscript's result tables, figures and inline macros.

    python scripts/make_results_assets.py

Companion to make_paper_assets.py (which covers dataset-level descriptives) and
make_qualitative_figures.py (which covers imagery). Everything here comes from
the experiment outputs, so no number in the results section is typed by hand.

Writes into the manuscript directory:
    tables/gate_matrix.tex          the train x test matrix, both datasets
    tables/annotation_only.tex      4b: trained ON A-only
    tables/positive_control.tex     4c: the strength sweep
    figures/fig4_sensitivity.pdf    the calibration curve -- the paper's key figure
    generated/results_values.tex    inline macros
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

import numpy as np
import pandas as pd

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

RUNS = REPO / "runs"
STRENGTHS = ["1.0", "0.75", "0.5", "0.25"]
PRETTY = {"fetal_planes": "FETAL\\_PLANES\\_DB", "bus_bra": "BUS-BRA"}
VARIANT_LABEL = {
    "a_full": "\\Afull{}",
    "a_removed": "\\Aremoved{}",
    "a_only": "\\Aonly{}",
    "ctrl_random": "\\Actrl{}",
    "a_full__nomarker": "\\Afull{} minus marker",
}


def find_paper_dir() -> Path:
    env = os.environ.get("ASA_PAPER_DIR")
    if env:
        return Path(env).expanduser().resolve()
    for candidate in (REPO / "paper", REPO.parent / "Manuscript"):
        if (candidate / "main.tex").exists():
            return candidate
    return REPO / "paper"


def real_rows(frame: pd.DataFrame) -> pd.DataFrame:
    flag = frame.get("is_contrast", pd.Series(False, index=frame.index))
    return frame[~flag.fillna(False).astype(bool)]


def load(path: Path) -> pd.DataFrame | None:
    csv = path / "matrix_results.csv"
    return real_rows(pd.read_csv(csv)) if csv.exists() else None


def cell(frame: pd.DataFrame, variant: str, column: str = "balanced_accuracy") -> float:
    subset = frame[frame.test_variant == variant]
    return float(subset[column].mean()) if len(subset) else float("nan")


def cell_sd(frame: pd.DataFrame, variant: str) -> float:
    subset = frame[frame.test_variant == variant]
    return float(subset.balanced_accuracy.std()) if len(subset) > 1 else float("nan")


def paired_drop(frame: pd.DataFrame, a: str, b: str) -> tuple[float, float]:
    """Mean and SD of (a - b) paired on (fold, seed).

    Paired, because both cells come from the same weights on the same patients;
    an unpaired difference would carry between-run variance that cancels exactly.
    """
    pivot = frame.pivot_table(index=["fold", "seed"], columns="test_variant", values="balanced_accuracy")
    if a not in pivot or b not in pivot:
        return float("nan"), float("nan")
    diff = (pivot[a] - pivot[b]).dropna()
    return float(diff.mean()), float(diff.std())


