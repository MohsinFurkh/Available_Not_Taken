def fig_sensitivity(out: Path, curve: list, real_drop: float, run_sd: float) -> None:
    """Removal cost against marker--label correlation, with the real annotations
    placed on the same axis.

    This is the paper's central figure: it converts "we found nothing" into
    "we found nothing, and here is exactly how much we would have found".
    """
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    curve = sorted(curve, key=lambda c: c["strength"])
    x = [c["strength"] for c in curve]
    y = [c["drop"] for c in curve]
    err = [c["drop_sd"] if np.isfinite(c["drop_sd"]) else 0.0 for c in curve]

    fig, ax = plt.subplots(figsize=(5.4, 3.2))
    ax.axhspan(-2 * run_sd, 2 * run_sd, color="0.88", zorder=0,
               label=f"$\\pm2\\times$ run-to-run SD ({run_sd:.4f})")
    ax.errorbar(x, y, yerr=err, marker="o", capsize=3, linewidth=1.6,
                color="#1f77b4", label="synthetic shortcut", zorder=3)
    ax.axhline(real_drop, color="#d62728", linestyle="--", linewidth=1.6, zorder=2,
               label=f"real annotations ({real_drop:+.4f})")

    ax.set_xlabel("marker–label correlation (shortcut strength)", fontsize=9)
    ax.set_ylabel("cost of removing the feature\n(balanced accuracy)", fontsize=9)
    ax.set_xticks(x)
    ax.tick_params(labelsize=8)
    ax.spines[["top", "right"]].set_visible(False)
    ax.legend(fontsize=7.5, frameon=False, loc="upper left")
    fig.tight_layout()

    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out.with_suffix(".pdf"), bbox_inches="tight")
    fig.savefig(out.with_suffix(".png"), dpi=200, bbox_inches="tight")
    plt.close(fig)


